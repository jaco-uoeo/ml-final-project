# Read the data into a DataFrame
from io import StringIO

df = pd.read_csv(StringIO(data))

# clean up rate format
df["Rate"] = df["Rate"].astype(float)
df["Batch Normalise"] = df["Batch Normalise"].astype(str)
df["Image Gen"] = df["Image Gen"].astype(str)

# create a combination column
df["Combination"] = (
    df["Rate"].astype(str)
    + ", "
    + df["Batch Normalise"]
    + ", "
    + df["Image Gen"]
    + ", "
    + df["Dropout"]
)

# group by combinations and average results
summary_df = (
    df.groupby("Combination").agg({"Accuracy": "mean", "Loss": "mean"}).reset_index()
)

# sort to find best accuracy and lowest loss
summary_df_sorted = summary_df.sort_values(
    by=["Accuracy", "Loss"], ascending=[False, True]
)

plt.figure(figsize=(8, 6))
sns.scatterplot(
    data=summary_df_sorted,
    x="Loss",
    y="Accuracy",
    hue="Combination",
    legend=False,
    s=75,
)
# plt.title('All Results by Combination')
plt.xlabel("Loss", fontsize=14)
plt.ylabel("Accuracy", fontsize=14)
plt.tight_layout()
plt.tick_params(axis="both", labelsize=12)
plt.show()

# sort and get top 5 combinations
top_5_combinations = (
    summary_df.sort_values(by=["Accuracy", "Loss"], ascending=[False, True])
    .head(5)["Combination"]
    .tolist()
)

# filter original data for only those top 5
top_df = df[df["Combination"].isin(top_5_combinations)]

plt.figure(figsize=(8, 5))
sns.scatterplot(
    data=top_df, x="Loss", y="Accuracy", hue="Combination", palette="Set2", s=400
)

# plt.title('Top 5 Performing Combinations')
plt.xlabel("Loss", fontsize=14)
plt.ylabel("Accuracy", fontsize=14)
plt.legend(
    title="LR, Normalise, ImGen, Dropout",
    bbox_to_anchor=(1.05, 1),
    loc="upper left",
    handleheight=2.5,
    labelspacing=1.2,
)
plt.tight_layout()
plt.tick_params(axis="both", labelsize=12)
plt.show()

csv_output = top_df.to_csv(index=False)
print(csv_output)
